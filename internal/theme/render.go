const genHeader = "generated by `dotfiles theme` — do not edit, switching themes overwrites it"

// Wezterm renders ~/.config/wezterm/theme.lua; wezterm.lua requires it and
// falls back to its built-in scheme when absent. wezterm auto-reloads.
func Wezterm(p *Palette) string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- %s\n-- theme: %s (%s)\nreturn {\n\tname = %q,\n\tcolors = {\n", genHeader, p.Name, p.Label, p.Name)
	fmt.Fprintf(&b, "\t\tforeground = %q,\n\t\tbackground = %q,\n", p.Primary.Foreground, p.Primary.Background)
	fmt.Fprintf(&b, "\t\tcursor_bg = %q,\n\t\tcursor_fg = %q,\n\t\tcursor_border = %q,\n", p.Cursor.Cursor, p.Cursor.Text, p.Cursor.Cursor)
	fmt.Fprintf(&b, "\t\tselection_fg = %q,\n\t\tselection_bg = %q,\n", p.Selection.Text, p.Selection.Background)
	ansi := func(key string, a *ANSI) {
		fmt.Fprintf(&b, "\t\t%s = {\n", key)
		for _, c := range []string{a.Black, a.Red, a.Green, a.Yellow, a.Blue, a.Magenta, a.Cyan, a.White} {
			fmt.Fprintf(&b, "\t\t\t%q,\n", c)
		}
		b.WriteString("\t\t},\n")
	}
	ansi("ansi", &p.Normal)
	ansi("brights", &p.Bright)
	b.WriteString("\t},\n}\n")
	return b.String()
}

// ZellijTheme renders themes/<name>.kdl (committed repo asset).
func ZellijTheme(p *Palette) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s (%s) — generated from themes/%s/palette.toml, do not edit by hand\nthemes {\n    %s {\n", p.Label, p.Source, p.Name, p.Name)
	rows := [][2]string{
		{"fg", p.Primary.Foreground}, {"bg", p.Primary.Background},
		{"black", p.Normal.Black}, {"red", p.Normal.Red}, {"green", p.Normal.Green},
		{"yellow", p.Normal.Yellow}, {"blue", p.Normal.Blue}, {"magenta", p.Normal.Magenta},
		{"cyan", p.Normal.Cyan}, {"white", p.Normal.White}, {"orange", p.Roles.Warn},
	}
	for _, r := range rows {
		fmt.Fprintf(&b, "        %s %q\n", r[0], r[1])
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

// ZjstatusLayout renders the live zellij layouts/default.kdl with the
// palette applied to the status-bar colors.
func ZjstatusLayout(p *Palette) string {
	repl := strings.NewReplacer(
		"{{accent}}", p.Roles.Accent,
		"{{warn}}", p.Roles.Warn,
		"{{error}}", p.Roles.Error,
		"{{dim}}", p.Roles.Dim,
		"{{line}}", p.Roles.Line,
		"{{sel}}", p.Roles.Sel,
	)
	return "// " + genHeader + " (theme: " + p.Name + ")\n" + repl.Replace(zjstatusTemplate)
}

