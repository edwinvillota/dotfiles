// NvimActive renders ~/.config/nvim/lua/config/theme-active.lua, read by
// nvim/lua/plugins/colorscheme.lua (falls back to ayu-dark when absent).
func NvimActive(p *Palette) string {
	return fmt.Sprintf("-- %s\nreturn { colorscheme = %q }\n", genHeader, p.Nvim)
}

// ZshEnv renders ~/.config/zsh/00-theme.zsh (sourced first by the modular
// loop in .zshrc). BAT_THEME=ansi makes bat inherit the terminal palette so
// it matches every theme with no extra assets.
func ZshEnv(p *Palette) string {
	fzf := strings.Join([]string{
		"bg:" + p.Primary.Background, "fg:" + p.Primary.Foreground,
		"bg+:" + p.Roles.Sel, "fg+:" + p.Primary.Foreground,
		"hl:" + p.Roles.Accent, "hl+:" + p.Roles.Accent,
		"info:" + p.Roles.Dim, "border:" + p.Roles.Line,
		"prompt:" + p.Roles.Accent2, "pointer:" + p.Roles.Accent,
		"marker:" + p.Roles.Good, "spinner:" + p.Roles.Accent2,
		"header:" + p.Roles.Dim,
	}, ",")
	return fmt.Sprintf("# %s\n# theme: %s (%s)\nexport BAT_THEME=ansi\nexport FZF_DEFAULT_OPTS=\"--color=%s\"\n", genHeader, p.Name, p.Label, fzf)
}

